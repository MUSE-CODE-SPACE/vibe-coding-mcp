function startOfDay(d: Date): Date {
  const x = new Date(d);
  x.setHours(0, 0, 0, 0);
  return x;
}

function addDays(d: Date, n: number): Date {
  const x = new Date(d);
  x.setDate(x.getDate() + n);
  return x;
}

function startOfWeek(d: Date): Date {
  // Monday-based week.
  const x = startOfDay(d);
  const day = (x.getDay() + 6) % 7;
  return addDays(x, -day);
}

export function resolveRange(input: DigestInput, now: Date = new Date()): { since: Date; until: Date; period: DigestPeriod } {
  const period: DigestPeriod = input.period ?? (input.since || input.until ? 'custom' : 'week');
  const today = startOfDay(now);
  switch (period) {
    case 'today':
      return { since: today, until: addDays(today, 1), period };
    case 'yesterday':
      return { since: addDays(today, -1), until: today, period };
    case 'week':
      return { since: startOfWeek(now), until: addDays(startOfWeek(now), 7), period };
    case 'last-week': {
      const thisWeek = startOfWeek(now);
      return { since: addDays(thisWeek, -7), until: thisWeek, period };
    }
    case 'month': {
      const since = new Date(now.getFullYear(), now.getMonth(), 1);
      const until = new Date(now.getFullYear(), now.getMonth() + 1, 1);
      return { since, until, period };
    }
    case 'custom':
    default: {
      const since = input.since ? new Date(input.since) : addDays(today, -7);
      const until = input.until ? new Date(input.until) : addDays(today, 1);
      if (Number.isNaN(since.getTime()) || Number.isNaN(until.getTime())) {
        throw new Error('since/until must be ISO dates (YYYY-MM-DD)');
      }
      return { since, until, period: 'custom' };
    }
  }
}

function sessionDate(s: SessionData): string {
  const meta = (s.metadata ?? {}) as Record<string, unknown>;
  const started = typeof meta.startedAt === 'string' ? meta.startedAt : s.createdAt;
  return started.slice(0, 10);
}

function toSummary(s: SessionData): DigestSessionSummary {
  const meta = (s.metadata ?? {}) as Record<string, unknown>;
  const filesTouched = Array.isArray(meta.filesTouched)
    ? (meta.filesTouched as unknown[]).filter((f): f is string => typeof f === 'string')
    : s.codeContexts.flatMap((c) => c.codeBlocks.map((b) => b.filename).filter((f): f is string => !!f));
  return {
    id: s.id,
    title: s.title,
    date: sessionDate(s),
    project: typeof meta.project === 'string' ? meta.project : undefined,
    gitBranch: typeof meta.gitBranch === 'string' ? meta.gitBranch : undefined,
    durationSec: typeof meta.durationSec === 'number' ? meta.durationSec : undefined,
    promptCount: typeof meta.promptCount === 'number' ? meta.promptCount : undefined,
    filesTouched: [...new Set(filesTouched)],
    decisionTitles: s.designDecisions.map((d) => d.title),
    tags: s.tags ?? [],
  };
}

function fmtDuration(sec: number): string {
  if (sec < 60) return `${sec}s`;
  const m = Math.round(sec / 60);
  if (m < 60) return `${m}m`;
  return `${Math.floor(m / 60)}h ${m % 60}m`;
}

function extractAsks(s: SessionData, max = 3): string[] {
  const idx = s.summary.indexOf('What was asked:');
  if (idx < 0) return [];
  return s.summary
    .slice(idx)
    .split('\n')
    .slice(1)
    .filter((l) => l.startsWith('- ') && !l.startsWith('- …'))
    .slice(0, max)
    .map((l) => l.slice(2));
}

export function renderDigestMarkdown(
  out: Omit<DigestOutput, 'content' | 'success'>,
  fullSessions: Map<string, SessionData>,
  input: DigestInput,
): string {
  const L = STRINGS[input.language ?? 'en'];
  const groupBy = input.groupBy ?? 'day';
  const lines: string[] = [];
  const sinceStr = out.range.since.slice(0, 10);
  const untilStr = new Date(new Date(out.range.until).getTime() - 1).toISOString().slice(0, 10);

  lines.push(`# ${input.title ?? L.title} — ${sinceStr}${untilStr !== sinceStr ? ` → ${untilStr}` : ''}`);
  lines.push('');

  if (out.totals.sessions === 0) {
    lines.push(L.noSessions);
    return lines.join('\n');
  }

  lines.push(
    `**${out.totals.sessions} ${L.sessions}** · **${fmtDuration(out.totals.durationSec)} ${L.time}** · ` +
      `**${out.totals.uniqueFiles} ${L.files}** · **${out.totals.designDecisions} ${L.decisions}** · ` +
      `**${out.totals.prompts} ${L.prompts}**` +
      (out.totals.projects.length ? ` · ${L.projects}: ${out.totals.projects.join(', ')}` : ''),
  );
  lines.push('');

  // Highlights: top decisions across all sessions (first 8).
  const allDecisions = [...fullSessions.values()].flatMap((s) =>
    s.designDecisions.map((d) => ({ ...d, session: s.title })),
  );
  if ((input.includeDecisions ?? true) && allDecisions.length) {
    lines.push(`## ${L.highlights}`);
    lines.push('');
    for (const d of allDecisions.slice(0, 8)) {
      lines.push(`- **${d.title}** — ${d.description}${d.rationale ? ` _(${d.rationale})_` : ''}`);
    }
    lines.push('');
  }

  lines.push(`## ${L.byGroup[groupBy]}`);
  lines.push('');
  for (const group of out.groups) {
    if (groupBy !== 'none') {
      lines.push(`### ${group.key}`);
      lines.push('');
    }
    for (const s of group.sessions) {
      const meta: string[] = [];
      if (s.project && groupBy !== 'project') meta.push(s.project);
      if (s.gitBranch) meta.push(`\`${s.gitBranch}\``);
      if (s.durationSec !== undefined) meta.push(fmtDuration(s.durationSec));
      if (groupBy !== 'day') meta.push(s.date);
      lines.push(`- **${s.title}**${meta.length ? ` (${meta.join(' · ')})` : ''}`);

      const full = fullSessions.get(s.id);
      if ((input.includePrompts ?? false) && full) {
        for (const ask of extractAsks(full)) lines.push(`  - ${L.asked}: ${ask}`);
      }
      if ((input.includeFiles ?? true) && s.filesTouched.length) {
        const shown = s.filesTouched.slice(0, 6).map((f) => `\`${f}\``).join(', ');
        const more = s.filesTouched.length > 6 ? ` +${s.filesTouched.length - 6}` : '';
        lines.push(`  - ${L.filesHeading}: ${shown}${more}`);
      }
      if ((input.includeDecisions ?? true) && s.decisionTitles.length) {
        lines.push(`  - ${L.decisionsHeading}: ${s.decisionTitles.slice(0, 4).join('; ')}`);
      }
    }
    lines.push('');
  }

  if ((input.includeFiles ?? true) && out.topFiles.length) {
    lines.push(`## ${L.topFiles}`);
    lines.push('');
    for (const f of out.topFiles.slice(0, 10)) lines.push(`- \`${f.file}\` — ${f.sessions}×`);
    lines.push('');
  }

  lines.push('---');
  lines.push(`*${L.generated} · ${new Date().toISOString()}*`);
  return lines.join('\n');
}

export async function digestTool(input: DigestInput): Promise<DigestOutput> {
  const empty: DigestOutput['totals'] = {
    sessions: 0, durationSec: 0, filesTouched: 0, uniqueFiles: 0, designDecisions: 0, prompts: 0, projects: [],
  };
  let range: { since: Date; until: Date; period: DigestPeriod };
  try {
    range = resolveRange(input);
  } catch (err) {
    return {
      success: false, period: 'custom', range: { since: '', until: '' }, totals: empty, groups: [], topFiles: [],
      error: (err as Error).message,
    };
  }

  try {
    const { sessions: stored } = await listSessions({ limit: 10000, sortBy: 'createdAt', sortOrder: 'asc' });
    const full = new Map<string, SessionData>();
    const picked: DigestSessionSummary[] = [];

    for (const s of stored) {
      const meta = (s.metadata ?? {}) as Record<string, unknown>;
      const startedAt = typeof meta.startedAt === 'string' ? meta.startedAt : s.createdAt;
      const t = new Date(startedAt).getTime();
      if (!(t >= range.since.getTime() && t < range.until.getTime())) continue;
      if (input.tags?.length && !input.tags.some((tag) => s.tags.includes(tag))) continue;
      if (input.project && meta.project !== input.project) continue;
      const data = await getSession(s.id);
      if (!data) continue;
      full.set(data.id, data);
      picked.push(toSummary(data));
      if (input.maxSessions && picked.length >= input.maxSessions) break;
    }

    const fileCount = new Map<string, number>();
    const projects = new Set<string>();
    let durationSec = 0;
    let decisions = 0;
    let prompts = 0;
    let filesTouched = 0;
    for (const s of picked) {
      durationSec += s.durationSec ?? 0;
      decisions += s.decisionTitles.length;
      prompts += s.promptCount ?? 0;
      filesTouched += s.filesTouched.length;
      if (s.project) projects.add(s.project);
      for (const f of s.filesTouched) fileCount.set(f, (fileCount.get(f) || 0) + 1);
    }

    const groupBy = input.groupBy ?? 'day';
    const groupMap = new Map<string, DigestSessionSummary[]>();
    const keyFor = (s: DigestSessionSummary): string[] => {
      if (groupBy === 'day') return [s.date];
      if (groupBy === 'project') return [s.project ?? '(no project)'];
      if (groupBy === 'tag') {
        const userTags = s.tags.filter((t) => !['claude-code', 'auto-capture'].includes(t));
        return userTags.length ? userTags : ['(untagged)'];
      }
      return ['all'];
    };
    for (const s of picked) {
      for (const k of keyFor(s)) {
        if (!groupMap.has(k)) groupMap.set(k, []);
        groupMap.get(k)!.push(s);
      }
    }
    const groups = [...groupMap.entries()]
      .sort((a, b) => (groupBy === 'day' ? (a[0] < b[0] ? 1 : -1) : b[1].length - a[1].length))
      .map(([key, sessions]) => ({ key, sessions }));

    const base: Omit<DigestOutput, 'content' | 'success'> = {
      period: range.period,
      range: { since: range.since.toISOString(), until: range.until.toISOString() },
      totals: {
        sessions: picked.length,
        durationSec,
        filesTouched,
        uniqueFiles: fileCount.size,
        designDecisions: decisions,
        prompts,
        projects: [...projects].sort(),
      },
      groups,
      topFiles: [...fileCount.entries()]
        .sort((a, b) => b[1] - a[1])
        .slice(0, 10)
        .map(([file, sessions]) => ({ file, sessions })),
    };

    const content = (input.format ?? 'markdown') === 'markdown' ? renderDigestMarkdown(base, full, input) : undefined;
    return {
      success: true,
      ...base,
      content,
      message: `${picked.length} session(s) between ${base.range.since.slice(0, 10)} and ${base.range.until.slice(0, 10)}`,
    };
  } catch (err) {
    return {
      success: false, period: range.period,
      range: { since: range.since.toISOString(), until: range.until.toISOString() },
      totals: empty, groups: [], topFiles: [], error: (err as Error).message,
    };
  }
}

