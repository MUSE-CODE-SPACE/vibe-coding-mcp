/**
 * muse_digest — roll captured sessions over a time window into one
 * Markdown report (daily standup, weekly report, monthly retro), grouped by
 * day / project / tag. Reads only the local session store.
 */

import { listSessions, getSession, SessionData } from '../core/sessionStorage.js';

export type DigestPeriod = 'today' | 'yesterday' | 'week' | 'last-week' | 'month' | 'custom';
export type DigestGroupBy = 'day' | 'project' | 'tag' | 'none';

export interface DigestInput {
  period?: DigestPeriod;
  since?: string;
  until?: string;
  groupBy?: DigestGroupBy;
  language?: 'en' | 'ko';
  format?: 'markdown' | 'json';
  tags?: string[];
  project?: string;
  includeFiles?: boolean;
  includeDecisions?: boolean;
  includePrompts?: boolean;
  maxSessions?: number;
  title?: string;
}

export interface DigestSessionSummary {
  id: string;
  title: string;
  date: string;
  project?: string;
  gitBranch?: string;
  durationSec?: number;
  promptCount?: number;
  filesTouched: string[];
  decisionTitles: string[];
  tags: string[];
}

export interface DigestOutput {
  success: boolean;
  period: DigestPeriod;
  range: { since: string; until: string };
  totals: {
    sessions: number;
    durationSec: number;
    filesTouched: number;
    uniqueFiles: number;
    designDecisions: number;
    prompts: number;
    projects: string[];
  };
  groups: Array<{ key: string; sessions: DigestSessionSummary[] }>;
  topFiles: Array<{ file: string; sessions: number }>;
  content?: string;
  message?: string;
  error?: string;
}

